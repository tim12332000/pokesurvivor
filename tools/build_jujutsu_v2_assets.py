"""Register inspected JJK v2 animation art without repainting source pixels.

All raster artwork is generated by built-in image_gen. This step only copies
selected sources, detects transparent gutters, records crops and crops portraits.
"""
from __future__ import annotations
import hashlib
import json
import shutil
from pathlib import Path
from PIL import Image

ROOT=Path(__file__).resolve().parents[1]
ART=ROOT/'art-review'
DESIGN=ART/'jjk-art-v2'
COMMON=['idleFront','idleBack','idleSide','walkFrontA','walkFrontB','walkBackA','walkBackB','walkSideA','walkSideB','hurt','fall','down']
NAMES={
 'yuta-skills':['idleFront','walkSideA','walkSideB','bladeWindup','bladeSlash','bladeRecovery','speechWindup','speechRelease','speechRecovery','ringRaise','ringGlow','ringRecovery'],
 'ryu-skills':['idleFront','idleBack','idleSide','walkSideA','walkSideB','hurt','lightCharge','lightRelease','lightRecoil','maxCharge','maxRelease','maxRecoil'],
 'uro-skills':['idleFront','idleBack','screenHold','walkSideA','walkSideB','hurt','skyGrab','skyPull','skyRelease','iceWindup','iceContact','iceRecovery'],
 'rika-skills':['travelA','travelB','return','strikeWindup','strikeContact','strikeRecoil','manifestLoom1','manifestLoom2','manifestRoar']}
SOURCE_VERSIONS={'yuta-skills':3,'rika-skills':3}
# Inspected anatomical crown-to-feet height excludes Uro's floating tendrils
# and Ryu's tall pompadour extension. Crouched/down frames keep this denominator.
BODY_HEIGHTS={'yuta':330,'ryu':300,'uro':235,'rika':350}
POINTS={
 'ryu-skills':{
  'lightCharge':{'muzzle':[198,114]},
  'lightRelease':{'muzzle':[218,78],'beamEnd':[295,78]},
  'lightRecoil':{'muzzle':[136,60]},
  'maxCharge':{'muzzle':[215,114]},
  'maxRelease':{'muzzle':[235,88],'beamEnd':[363,88]},
  'maxRecoil':{'muzzle':[164,49]}},
 'yuta-skills':{
  'speechWindup':{'mouth':[91,122]},
  'speechRelease':{'mouth':[132,125]},
  'ringRaise':{'ring':[65,143]},
  'ringGlow':{'ring':[65,143]},
  'bladeSlash':{'bladeTip':[392,137]}}
}

def sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()

def gutter_cuts(mask,count,vertical):
    size=mask.height if vertical else mask.width
    projection=[]
    for p in range(size):
        stripe=mask.crop((0,p,mask.width,p+1) if vertical else (p,0,p+1,mask.height))
        projection.append(sum(stripe.getdata())//255)
    cuts=[0]
    for k in range(1,count):
        expected=size*k/count
        radius=size/count*(.34 if vertical else .28)
        lo=max(cuts[-1]+1,int(expected-radius));hi=min(size-1,int(expected+radius))
        cut=min(range(lo,hi+1),key=lambda p:(projection[p],abs(p-expected)))
        if projection[cut]>2:raise ValueError(f'Visible pixels across gutter: {vertical=} {expected=} {cut=} {projection[cut]=}')
        cuts.append(cut)
    return cuts+[size]

def register(key):
    version=SOURCE_VERSIONS.get(key,2)
    source=DESIGN/f'{key}-source-v{version}.png'
    target=ART/'redrawn'/f'jjk-{key}-v2.png'
    shutil.copyfile(source,target)
    image=Image.open(source).convert('RGBA');alpha=image.getchannel('A')
    if alpha.getextrema()!=(0,255):raise ValueError(f'{key} has no true transparency')
    mask=alpha.point(lambda a:255 if a>=40 else 0)
    rows=3 if key=='rika-skills' else 4
    # Rika's contact claw and looming skulls have staggered row gutters;
    # inspect each column independently rather than clipping a long claw.
    rika_columns=[round(image.width*k/3) for k in range(4)] if key=='rika-skills' else None
    rika_rows=[gutter_cuts(mask.crop((rika_columns[c],0,rika_columns[c+1],image.height)),rows,True) for c in range(3)] if rika_columns else None
    ys=None if rika_columns else gutter_cuts(mask,rows,True)
    names=COMMON if key.endswith('-common') else NAMES[key]
    frames=[]
    for row in range(rows):
        stripe=None if rika_columns else mask.crop((0,ys[row],mask.width,ys[row+1]))
        xs=rika_columns or gutter_cuts(stripe,3,False)
        for col in range(3):
            cell=(xs[col],rika_rows[col][row],xs[col+1],rika_rows[col][row+1]) if rika_columns else (xs[col],ys[row],xs[col+1],ys[row+1])
            box=mask.crop(cell).getbbox()
            if not box:raise ValueError((key,row,col,'empty'))
            left,top=cell[0]+box[0],cell[1]+box[1]
            right,bottom=cell[0]+box[2],cell[1]+box[3]
            w,h=right-left,bottom-top;name=names[len(frames)]
            anchor_x=w/2
            if not key.startswith('rika') and name not in ['down','fall']:
                solid=alpha.crop((left,top,right,bottom)).point(lambda a:255 if a>=180 else 0)
                feet=solid.crop((0,max(0,h-14),w,h)).getbbox()
                if feet:anchor_x=(feet[0]+feet[2])/2
            frame={'name':name,'rect':[left,top,w,h],'anchor':[anchor_x,h-1]}
            if name in POINTS.get(key,{}):frame['points']=POINTS[key][name]
            frames.append(frame)
    body=BODY_HEIGHTS[key.split('-')[0]]
    result={'source':f'redrawn/{target.name}','bodyHeight':body,'frames':frames,'dimensions':list(image.size)}
    provenance={'source':str(source.relative_to(ROOT)).replace('\\','/'),'sha256':sha(source),'runtimeSha256':sha(target),'physicalFrames':len(frames),'transparent':True}
    return result,provenance

def build():
    keys=[f'{slug}-common' for slug in ['yuta','ryu','uro']]+[f'{slug}-skills' for slug in ['yuta','ryu','uro','rika']]
    sheets={};sources={}
    for key in keys:sheets[key],sources[key]=register(key)
    animations={slug:{} for slug in ['yuta','ryu','uro','rika']}
    def anim(slug,name,key,frames,fps=9,loop=False):
        animations[slug][name]={'sheet':key,'frames':frames,'fps':fps,'loop':loop}
    for slug in ['yuta','ryu','uro']:
        key=f'{slug}-common'
        for name,frames in {'idleFront':[0],'idleBack':[1],'idleSide':[2],'walkFront':[3,4],'walkBack':[5,6],'walkSide':[7,8],'hurt':[9],'faint':[10,11]}.items():
            anim(slug,name,key,frames,9,name.startswith('walk') or name.startswith('idle'))
        frame=sheets[key]['frames'][0];x,y,w,h=frame['rect']
        im=Image.open(ART/sheets[key]['source']).convert('RGBA')
        im.crop((x,y,x+w,y+h)).save(ROOT/'.omx/naruto/portraits'/f'jjk-{slug}.png')
    for slug,name,frames in [('yuta','blade',[3,4,5]),('yuta','speech',[6,7,8]),('yuta','manifest',[9,10,11]),('ryu','light',[6,7,8]),('ryu','maximum',[9,10,11]),('uro','sky',[6,7,8]),('uro','thinIce',[9,10,11]),('uro','screen',[2]),('uro','collapse',[6,7,10,11]),('rika','travel',[0,1]),('rika','return',[2]),('rika','strike',[3,4,5]),('rika','manifest',[6,7,8])]:
        anim(slug,name,f'{slug}-skills',frames,8,slug=='rika' and name in ['travel','manifest'])
    metadata={'version':2,'sheets':sheets,'animations':animations,'limitations':['Front/back/right common directions are authored; left mirrors right.','Rika tail/muscular anatomy and opaque Uro sky wrapping are explicit stylized game adaptations.','Skill contact timing comes from combat phase/phaseAge, not sequence fps alone.'],'sourceResearch':['jjk-research-v2/sources.json','jjk-anime-references-v2/']}
    (ART/'jjk-skills-v2.json').write_text(json.dumps(metadata,ensure_ascii=False,indent=2),encoding='utf-8')
    prompts_path=DESIGN/'prompts-v2.json'
    references={}
    if prompts_path.exists():
        def collect(value):
            if isinstance(value,dict):
                for name,child in value.items():
                    if name=='refs':
                        for raw in child:
                            path=Path(raw)
                            if not path.is_absolute():path=ROOT/path
                            if path.is_file():references[str(path.relative_to(ROOT)).replace('\\','/')]=sha(path)
                    else:collect(child)
            elif isinstance(value,list):
                for child in value:collect(child)
        collect(json.loads(prompts_path.read_text(encoding='utf-8')))
    provenance={'generator':'built-in image_gen','prompts':'art-review/jjk-art-v2/prompts-v2.json','promptSha256':sha(prompts_path) if prompts_path.exists() else None,'references':references,'sources':sources,'archivedGeneratedSources':{p.name:sha(p) for p in DESIGN.glob('*-source-v*.png')},'processing':'Original alpha preserved; transparent-gutter crop metadata, no source repainting/resampling.','physicalFrames':sum(len(s['frames']) for s in sheets.values())}
    (DESIGN/'provenance-v2.json').write_text(json.dumps(provenance,indent=2),encoding='utf-8')
    print(json.dumps({'sheets':len(sheets),'physicalFrames':sum(len(s['frames']) for s in sheets.values()),'animations':sum(len(a) for a in animations.values())}))

if __name__=='__main__':build()
